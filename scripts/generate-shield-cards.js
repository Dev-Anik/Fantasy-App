// Generates one shield card background per club, in the club's colours, for
// the "shield" player card style. Run after changing src/kits.ts:
//   node scripts/generate-shield-cards.js
// Writes assets/images/card-shield/<CLUB>.svg and src/shieldCards.ts, which
// loads the PNG versions: run scripts/render-card-images.js afterwards.
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const kitsSource = fs.readFileSync(path.join(root, "src", "kits.ts"), "utf8");
// Outfield kits only (the goalkeeper table follows it in the file).
const outfield = kitsSource.split("GOALKEEPER_KIT_COLORS")[0];

const clubs = [];
const pattern = /^\s{2}([A-Z]{3}): \{([^}]*)\}/gm;
let match;
while ((match = pattern.exec(outfield))) {
  const shirt = (match[2].match(/shirt: "(#[0-9a-fA-F]{6})"/) || [])[1];
  const trim = (match[2].match(/trim: "(#[0-9a-fA-F]{6})"/) || [])[1];
  if (shirt) clubs.push({ code: match[1], shirt: shirt.toLowerCase(), trim: (trim || "#ffffff").toLowerCase() });
}

const mix = (hex, target, amount) => {
  const value = hex.replace("#", "");
  const out = [0, 2, 4].map((i) => {
    const channel = parseInt(value.slice(i, i + 2), 16);
    return Math.round(channel + (target - channel) * amount)
      .toString(16)
      .padStart(2, "0");
  });
  return `#${out.join("")}`;
};
const darken = (hex, amount) => mix(hex, 0, amount);
const lighten = (hex, amount) => mix(hex, 255, amount);

// White shirts say nothing about the club, and white text would not read on
// them: use the trim colour instead.
const clubColour = ({ shirt, trim }) => (shirt === "#ffffff" ? trim : shirt);

const OUTLINE =
  "M8 1.5 H92 Q98.5 1.5 98.5 8 V112 Q98.5 118.5 92 118.5 H8 Q1.5 118.5 1.5 112 V8 Q1.5 1.5 8 1.5 Z";

const svg = (colour) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 120" preserveAspectRatio="none">
  <!-- Generated by scripts/generate-shield-cards.js. Do not edit by hand. -->
  <defs>
    <linearGradient id="face" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="${darken(colour, 0.2)}" />
      <stop offset="55%" stop-color="${darken(colour, 0.45)}" />
      <stop offset="100%" stop-color="${darken(colour, 0.72)}" />
    </linearGradient>
    <radialGradient id="light" cx="70%" cy="25%" r="70%">
      <stop offset="0%" stop-color="#ffffff" stop-opacity="0.12" />
      <stop offset="100%" stop-color="#ffffff" stop-opacity="0" />
    </radialGradient>
  </defs>
  <path d="${OUTLINE}" fill="url(#face)" stroke="${lighten(colour, 0.25)}" stroke-width="2.4" stroke-linejoin="round" />
  <path d="${OUTLINE}" fill="url(#light)" />
</svg>
`;

const outDir = path.join(root, "assets", "images", "card-shield");
fs.mkdirSync(outDir, { recursive: true });
for (const club of clubs) {
  fs.writeFileSync(path.join(outDir, `${club.code}.svg`), svg(clubColour(club)));
}

const lines = clubs.map((club) => `  ${club.code}: require("../assets/images/card-shield/${club.code}.png"),`);
fs.writeFileSync(
  path.join(root, "src", "shieldCards.ts"),
  `// Generated by scripts/generate-shield-cards.js. Do not edit by hand.
// Shield player card backgrounds in each club's colours.
export const SHIELD_CARDS: Record<string, number> = {
${lines.join("\n")}
};
`,
);
console.log(`Generated ${clubs.length} club cards:`, clubs.map((c) => c.code).join(" "));
console.log("Now run: node scripts/render-card-images.js");
