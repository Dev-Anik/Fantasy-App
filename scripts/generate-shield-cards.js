// Generates one shield card background per club, in the club's colours, for
// the "shield" player card style:
//   node scripts/generate-shield-cards.js
// Writes assets/images/card-shield/<CLUB>.svg and src/shieldCards.ts, which
// loads the PNG versions: run scripts/render-card-images.js afterwards
// (node scripts/render-card-images.js card-shield/ for these alone).
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");

// Each club's card colour. Many clubs share a colour (eight reds, eight
// blues, three clarets), so within each family the colours are spread
// apart on purpose (towards orange, pink or wine; azure, royal, violet or
// teal; lighter or darker), so same-coloured clubs still tell apart.
const COLOURS = {
  // Reds
  ARS: "#ef0107", // scarlet
  NFO: "#a3001a", // deep crimson
  LIV: "#b8124a", // raspberry
  BRE: "#e8335f", // pink red
  MUN: "#e5501f", // orange red
  SOU: "#ff6b4a", // coral
  SUN: "#9a0f22", // wine
  BOU: "#6e0c10", // red-black
  // Blues
  CHE: "#034694", // royal
  EVE: "#2148c9", // bright royal
  BHA: "#0072ce", // azure
  TOT: "#132257", // navy
  LEI: "#2a2fb0", // indigo
  CRY: "#5b3fa3", // blue-purple
  IPS: "#3a7bc8", // steel blue
  LEE: "#1f6f8b", // teal blue
  // Clarets
  AVL: "#670e36", // claret
  WHU: "#8a2b3e", // rose claret
  BUR: "#5a1a5e", // plum
  // Ambers, golds, oranges
  HUL: "#f5a12d", // amber
  LUT: "#f26a1b", // orange
  WOL: "#e0b21a", // gold
  // Sky blues
  MCI: "#6cabdd", // sky
  COV: "#39a7c9", // cyan
  // Black and white
  FUL: "#4a4a4a", // grey
  NEW: "#1d1d1d", // black
};

const mix = (hex, target, amount) => {
  const value = hex.replace("#", "");
  const out = [0, 2, 4].map((i) => {
    const channel = parseInt(value.slice(i, i + 2), 16);
    return Math.round(channel + (target - channel) * amount)
      .toString(16)
      .padStart(2, "0");
  });
  return `#${out.join("")}`;
};
const darken = (hex, amount) => mix(hex, 0, amount);
const lighten = (hex, amount) => mix(hex, 255, amount);

const OUTLINE =
  "M8 1.5 H92 Q98.5 1.5 98.5 8 V112 Q98.5 118.5 92 118.5 H8 Q1.5 118.5 1.5 112 V8 Q1.5 1.5 8 1.5 Z";

const svg = (colour) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 120" preserveAspectRatio="none">
  <!-- Generated by scripts/generate-shield-cards.js. Do not edit by hand. -->
  <defs>
    <linearGradient id="face" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" stop-color="${darken(colour, 0.2)}" />
      <stop offset="55%" stop-color="${darken(colour, 0.45)}" />
      <stop offset="100%" stop-color="${darken(colour, 0.72)}" />
    </linearGradient>
    <radialGradient id="light" cx="70%" cy="25%" r="70%">
      <stop offset="0%" stop-color="#ffffff" stop-opacity="0.12" />
      <stop offset="100%" stop-color="#ffffff" stop-opacity="0" />
    </radialGradient>
  </defs>
  <path d="${OUTLINE}" fill="url(#face)" stroke="${lighten(colour, 0.25)}" stroke-width="2.4" stroke-linejoin="round" />
  <path d="${OUTLINE}" fill="url(#light)" />
</svg>
`;

const outDir = path.join(root, "assets", "images", "card-shield");
fs.mkdirSync(outDir, { recursive: true });
const codes = Object.keys(COLOURS).sort();
for (const code of codes) {
  fs.writeFileSync(path.join(outDir, `${code}.svg`), svg(COLOURS[code]));
}

const lines = codes.map((code) => `  ${code}: require("../assets/images/card-shield/${code}.png"),`);
fs.writeFileSync(
  path.join(root, "src", "shieldCards.ts"),
  `// Generated by scripts/generate-shield-cards.js. Do not edit by hand.
// Shield player card backgrounds in each club's colours.
export const SHIELD_CARDS: Record<string, number> = {
${lines.join("\n")}
};
`,
);
console.log(`Generated ${codes.length} club cards:`, codes.join(" "));
console.log("Now run: node scripts/render-card-images.js card-shield/");
